#!/usr/bin/env node
// Ports the Cardinal Quest content into Dawn's Atlas data folder.
//
//   node scripts/atlas-import-cardinal.mjs --src <cardinal-quest checkout> [--sources-md <file>]
//
// Reads data/locations.json, public/data.js, public/threads.js and tools/landmarks.py (for the
// coordinate-source column that data.js drops). It never writes to the source checkout.
// After writing it converts the new files back to Cardinal Quest's short-key shapes and checks
// they deep-equal the originals, so a clean exit means nothing was lost or reworded.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const flag = (name) => {
  const at = args.indexOf(name);
  return at >= 0 ? args[at + 1] : undefined;
};
const src = flag('--src');
if (!src) {
  console.error('usage: node scripts/atlas-import-cardinal.mjs --src <cardinal-quest checkout> [--sources-md <file>]');
  process.exit(2);
}
const sourcesMd = flag('--sources-md');
const out = path.resolve('src/features/atlas/data/cardinal');
mkdirSync(out, { recursive: true });

const PROVENANCE = {
  repo: 'Artometrics/cardinal-quest',
  commit: 'ff16ac46624e77c9904118487080f7bef48f40ea',
  note: 'Ported field for field. Story text, sources, quiz answers, route lines and notes are unchanged. Nothing here is a new historical claim.',
};

function evalConsts(file, names) {
  const code = readFileSync(file, 'utf8');
  return new Function(`${code}\nreturn { ${names.join(', ')} };`)();
}

const { SPOTS, ROUTES, EVENTS } = evalConsts(path.join(src, 'public/data.js'), ['SPOTS', 'ROUTES', 'EVENTS']);
const { THREADS } = evalConsts(path.join(src, 'public/threads.js'), ['THREADS']);
const locationsRaw = readFileSync(path.join(src, 'data/locations.json'), 'utf8');

const coords = JSON.parse(
  execFileSync(
    'python3',
    ['-c', "import json,sys; sys.path.insert(0,'tools'); import landmarks as L; print(json.dumps({s['id']: s['coord'] for s in L.SPOTS}))"],
    { cwd: src, encoding: 'utf8' },
  ),
);

const ADDED_IN = { 0: 'v0', 1: 'v0.2', 3: 'v0.3' };
const source = (s) => ({ title: s.t, url: s.u });

const stops = SPOTS.map((s) => {
  assert.ok(s.id in coords, `no coordinate source for ${s.id}`);
  assert.ok(s.new in ADDED_IN, `unknown release marker ${s.new} on ${s.id}`);
  return {
    id: s.id,
    name: s.n,
    icon: s.i,
    lat: s.lat,
    lng: s.lng,
    years: s.y,
    sortYear: s.ty,
    addedIn: ADDED_IN[s.new],
    coordinateSource: coords[s.id],
    locationId: s.loc ?? null,
    story: s.h,
    facts: s.k,
    sources: s.s.map(source),
    quiz: { question: s.q.q, answers: s.q.a, correct: s.q.c },
  };
});

const routes = ROUTES.map((r) => ({
  id: r.id,
  name: r.n,
  icon: r.i,
  color: r.c,
  description: r.d,
  stops: r.stops,
  km: r.km,
  line: r.line,
  ...(r.bridge ? { bridge: r.bridge } : {}),
  ...(r.outro ? { outro: r.outro } : {}),
  ...(r.prologue ? { prologue: { text: r.prologue.t, sources: r.prologue.s.map(source) } } : {}),
  ...(r.side ? { side: { stopId: r.side.id, text: r.side.t } } : {}),
}));

const dailyNote = readFileSync(path.join(src, 'tools/threads.py'), 'utf8').match(/^DAILY_NOTE="(.*)"$/m)?.[1];
assert.ok(dailyNote, 'DAILY_NOTE not found in tools/threads.py');

const threads = THREADS.map((t) => ({
  id: t.id,
  name: t.n,
  icon: t.i,
  color: t.c,
  book: t.book,
  description: t.d,
  stops: t.stops,
  facts: t.f.map((f) => ({ text: f.t, sources: f.s.map(source) })),
}));

const events = EVENTS.map((e) => ({ year: e.y, text: e.t, stopId: e.l, source: source(e.s) }));

const meta = { ...PROVENANCE };
const write = (name, value) => writeFileSync(path.join(out, name), `${JSON.stringify(value, null, 1)}\n`);
writeFileSync(path.join(out, 'locations.json'), locationsRaw);
write('stops.json', { _meta: meta, stops });
write('routes.json', { _meta: meta, routes });
write('threads.json', { _meta: meta, dailyNote, threads });
write('events.json', { _meta: meta, events });

if (sourcesMd) {
  const body = readFileSync(sourcesMd, 'utf8');
  writeFileSync(
    path.join(out, 'SOURCES.md'),
    `<!-- Generated by Cardinal Quest's tools/build.py at ${PROVENANCE.repo}@${PROVENANCE.commit.slice(0, 7)} and copied here unchanged. -->\n${body}`,
  );
} else if (!existsSync(path.join(out, 'SOURCES.md'))) {
  console.warn('no --sources-md given, so SOURCES.md was not written');
}

// Round trip: new shapes back to the old ones.
const back = {
  spots: stops.map((s) => ({
    id: s.id,
    n: s.name,
    i: s.icon,
    lat: s.lat,
    lng: s.lng,
    y: s.years,
    h: s.story,
    k: s.facts,
    s: s.sources.map((x) => ({ t: x.title, u: x.url })),
    q: { q: s.quiz.question, a: s.quiz.answers, c: s.quiz.correct },
    new: Object.keys(ADDED_IN).find((k) => ADDED_IN[k] === s.addedIn) * 1,
    ty: s.sortYear,
    ...(s.locationId ? { loc: s.locationId } : {}),
  })),
  threads: threads.map((t) => ({
    id: t.id,
    n: t.name,
    i: t.icon,
    c: t.color,
    book: t.book,
    d: t.description,
    stops: t.stops,
    f: t.facts.map((f) => ({ t: f.text, s: f.sources.map((x) => ({ t: x.title, u: x.url })) })),
  })),
  events: events.map((e) => ({ y: e.year, t: e.text, l: e.stopId, s: { t: e.source.title, u: e.source.url } })),
};
assert.deepEqual(back.spots, SPOTS, 'stops differ from data.js');
assert.deepEqual(back.threads, THREADS, 'threads differ from threads.js');
assert.deepEqual(back.events, EVENTS, 'events differ from data.js');
assert.deepEqual(
  routes.map((r) => ({ ...r, line: r.line.length })),
  ROUTES.map((r) => ({
    id: r.id,
    name: r.n,
    icon: r.i,
    color: r.c,
    description: r.d,
    stops: r.stops,
    km: r.km,
    line: r.line.length,
    ...(r.bridge ? { bridge: r.bridge } : {}),
    ...(r.outro ? { outro: r.outro } : {}),
    ...(r.prologue ? { prologue: { text: r.prologue.t, sources: r.prologue.s.map(source) } } : {}),
    ...(r.side ? { side: { stopId: r.side.id, text: r.side.t } } : {}),
  })),
);
for (const [i, r] of routes.entries()) assert.deepEqual(r.line, ROUTES[i].line, `route line differs: ${r.id}`);

console.log(`ported ${stops.length} stops, ${routes.length} routes, ${threads.length} threads, ${events.length} events, ${JSON.parse(locationsRaw).locations.length} catalog places`);
console.log('round trip matches Cardinal Quest data.js and threads.js');
